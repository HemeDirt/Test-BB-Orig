def make_cfg(**overrides):
    """Копия дефолтов с переопределениями; неизвестный ключ — ошибка (гард от опечаток в флагах)."""
    bad = [k for k in overrides if k not in CFG_DEFAULTS]
    if bad:
        raise KeyError(f"неизвестный флаг CFG: {bad}")
    cfg = dict(CFG_DEFAULTS)
    cfg.update(overrides)
    return cfg
